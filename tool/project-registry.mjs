import { readFileSync } from "node:fs";

const projectSlugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const environmentPattern = /^apps-script(?:-[a-z0-9]+)*-production$/;
const releaseTagPattern = /^v[0-9]+\.[0-9]+\.[0-9]+$/;
const scriptIdPattern = /^[A-Za-z0-9_-]{20,}$/;
const spreadsheetIdPattern = /^[A-Za-z0-9_-]{20,}$/;

const defaultRegistryUrl = new URL("../projects.json", import.meta.url);

function requireObject(value, message) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(message);
  }

  return value;
}

export function parseProjectRegistry(value) {
  const registry = requireObject(value, "Project registry must be an object.");

  if (!Array.isArray(registry.projects) || registry.projects.length === 0) {
    throw new Error("Project registry must contain at least one project.");
  }

  const slugs = new Set();
  const environments = new Set();

  const projects = registry.projects.map((entry, index) => {
    const project = requireObject(
      entry,
      "Project registry entry " + (index + 1) + " must be an object.",
    );

    const { slug, environment } = project;

    if (typeof slug !== "string" || !projectSlugPattern.test(slug)) {
      throw new Error(
        "Project registry entry " + (index + 1) + " has an invalid slug.",
      );
    }

    if (
      typeof environment !== "string" ||
      !environmentPattern.test(environment)
    ) {
      throw new Error(
        'Project "' + slug + '" has an invalid GitHub Environment name.',
      );
    }

    if (slugs.has(slug)) {
      throw new Error('Project slug "' + slug + '" is duplicated.');
    }

    if (environments.has(environment)) {
      throw new Error(
        'GitHub Environment "' + environment + '" is assigned more than once.',
      );
    }

    slugs.add(slug);
    environments.add(environment);

    return Object.freeze({ slug, environment });
  });

  return Object.freeze(projects);
}

export function loadProjectRegistry(registryUrl = defaultRegistryUrl) {
  return parseProjectRegistry(JSON.parse(readFileSync(registryUrl, "utf8")));
}

export function validateReleaseTag(tag) {
  if (typeof tag !== "string" || !releaseTagPattern.test(tag)) {
    throw new Error("Production tags must use vX.Y.Z format.");
  }

  return tag;
}

export function createDeploymentMatrix(projects = loadProjectRegistry()) {
  return Object.freeze({
    include: projects.map((project) => ({
      project: project.slug,
      environment: project.environment,
    })),
  });
}

export function createClaspConfig(scriptId) {
  if (typeof scriptId !== "string" || !scriptIdPattern.test(scriptId)) {
    throw new Error("APPS_SCRIPT_ID is missing or invalid.");
  }

  return Object.freeze({
    scriptId,
    rootDir: "src",
  });
}

export function createTargetSource(spreadsheetId, spreadsheetTitle) {
  if (
    typeof spreadsheetId !== "string" ||
    !spreadsheetIdPattern.test(spreadsheetId)
  ) {
    throw new Error("SPREADSHEET_ID is missing or invalid.");
  }

  if (typeof spreadsheetTitle !== "string" || !spreadsheetTitle.trim()) {
    throw new Error("SPREADSHEET_TITLE is missing or invalid.");
  }

  const target = JSON.stringify({ id: spreadsheetId, title: spreadsheetTitle });

  return [
    "// Generated by `npm run project:configure`. Do not commit.",
    "const TARGET_SPREADSHEET = Object.freeze(" + target + ");",
    "",
  ].join("\n");
}
